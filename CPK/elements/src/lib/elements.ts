/**
 * Get element by atomic number
 */
export function getElement(atomicNumber: number): ElementData | undefined {
  return PERIODIC_TABLE.find(el => el.atomicNumber === atomicNumber);
}

/**
 * Get element by symbol
 */
export function getElementBySymbol(symbol: string): ElementData | undefined {
  return PERIODIC_TABLE.find(el => el.symbol === symbol);
}

/**
 * Get elements by category
 */
export function getElementsByCategory(category: ElementCategory): ElementData[] {
  return PERIODIC_TABLE.filter(el => el.category === category);
}

/**
 * Calculate theoretical orbital radii based on Bohr model
 * Used for visualization before quantum simulation
 */
export function calculateBohrRadii(atomicNumber: number, maxOrbital: number = 4): number[] {
  const bohrRadius = 0.529; // Angstroms (Å)
  const radii: number[] = [];
  
  for (let n = 1; n <= maxOrbital; n++) {
    radii.push(bohrRadius * (n * n) / atomicNumber);
  }
  
  return radii;
}

/**
 * Generate electron configuration orbital positions
 * Creates a preliminary 3D spatial distribution for visualization
 */
export function generateElectronPositions(
  atomicNumber: number,
  orbitsCount: number = 3
): Vector3[] {
  const positions: Vector3[] = [];
  const radii = calculateBohrRadii(atomicNumber, orbitsCount);
  
  // Simple spherical distribution for each orbital
  for (let orbitIdx = 0; orbitIdx < radii.length; orbitIdx++) {
    const radius = radii[orbitIdx];
    const electronsInOrbit = Math.min(2 * (2 * (orbitIdx + 1) ** 2), atomicNumber - positions.length);
    
    for (let i = 0; i < electronsInOrbit; i++) {
      const phi = (i / electronsInOrbit) * 2 * Math.PI;
      const theta = Math.acos(2 * (i / electronsInOrbit) - 1);
      
      positions.push({
        x: radius * Math.sin(theta) * Math.cos(phi),
        y: radius * Math.sin(theta) * Math.sin(phi),
        z: radius * Math.cos(theta),
      });
    }
  }
  
  return positions;
}

/**
 * Mock quantum model data (will be replaced with Q# simulations)
 */
export function createMockModelData(element: ElementData): ModelData {
  const orbitalCount = Math.ceil(Math.sqrt(element.atomicNumber));
  const radii = calculateBohrRadii(element.atomicNumber, orbitalCount);
  
  return {
    orbitalRadii: radii,
    electronPositions: generateElectronPositions(element.atomicNumber, orbitalCount),
    energyLevels: radii.map((_, i) => -13.6 / ((i + 1) ** 2)), // Rydberg formula
    quantumNumbers: generateQuantumNumbers(element.atomicNumber),
  };
}

/**
 * Generate quantum numbers for each electron
 */
export function generateQuantumNumbers(atomicNumber: number): QuantumNumber[] {
  const numbers: QuantumNumber[] = [];
  let electronsAdded = 0;
  
  for (let n = 1; n <= 7 && electronsAdded < atomicNumber; n++) {
    for (let l = 0; l < n && electronsAdded < atomicNumber; l++) {
      for (let ml = -l; ml <= l && electronsAdded < atomicNumber; ml++) {
        for (let ms of [-0.5, 0.5]) {
          if (electronsAdded < atomicNumber) {
            numbers.push({ n, l, ml, ms });
            electronsAdded++;
          }
        }
      }
    }
  }
  
  return numbers;
}
