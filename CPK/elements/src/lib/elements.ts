/**
 * Element Data Structure for the Periodic Table
 * Contains atomic properties and visualization data for each element
 */

export interface ElementData {
  atomicNumber: number;
  symbol: string;
  name: string;
  atomicMass: number;
  category: ElementCategory;
  electronConfig: string;
  electronegativity: number | null;
  ionizationEnergy: number; // eV
  atomicRadius: number; // pm
  density: number; // g/cm³
  meltingPoint: number; // K
  boilingPoint: number; // K
  oxidationStates: number[];
  yearDiscovered: number;
  color: string; // hex color for visualization
  modelData?: ModelData;
}

export type ElementCategory = 
  | "nonmetal"
  | "alkaliMetal"
  | "alkalineEarthMetal"
  | "lanthanide"
  | "actinide"
  | "transitionMetal"
  | "postTransitionMetal"
  | "semimetal"
  | "halogen"
  | "nobleGas";

export interface ModelData {
  orbitalRadii: number[]; // Bohr radii for electron orbitals
  electronPositions: Vector3[];
  energyLevels: number[];
  quantumNumbers: QuantumNumber[];
}

export interface QuantumNumber {
  n: number; // principal quantum number
  l: number; // angular momentum quantum number
  ml: number; // magnetic quantum number
  ms: number; // spin magnetic quantum number
}

export interface Vector3 {
  x: number;
  y: number;
  z: number;
}

export interface SimulationResult {
  elementSymbol: string;
  atomicNumber: number;
  probabilityMap: number[][]; // 3D probability distribution
  groundStateEnergy: number; // eV
  spatialData: SpatialPoint[];
  molecularBonds?: BondData[];
}

export interface SpatialPoint {
  position: Vector3;
  probability: number;
  phase: number;
}

export interface BondData {
  element1: string;
  element2: string;
  bondType: "covalent" | "ionic" | "metallic";
  bondEnergy: number;
  bondLength: number; // pm
}

